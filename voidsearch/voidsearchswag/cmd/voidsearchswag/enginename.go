package main

import (
	"strings"
)

// displayEngineName укорачивает имя движка для вывода, оставляя сами данные
// нетронутыми.
//
// Проблема: имя движка одновременно служит ключом в пуле здоровья, поэтому оно
// обязано быть уникальным и детерминированным (promote.engineName берёт первую
// метку хоста). Для v3 onion-адреса это все 56 символов base32. Живой прогон
// deep-режима печатал строку отчёта:
//
//	движки: torch:16, tornet:8, tor66:40, 2222222o2mfta3jpjvymjr6jiwmmuyvouq2huakwcxu5tjdwj3egovad:281, ahmia-clear:fail
//
// Одна такая запись длиннее всех остальных вместе взятых и ломает строку на
// перенос, поэтому отчёт перестаёт читаться.
//
// Укорачивать само имя нельзя: при коллизии два движка перетрут друг друга в
// пуле здоровья, и один молча перестанет опрашиваться. Поэтому укорачивается
// только печать, а в JSON, в базу и в Result.Source уходит полное имя.
//
// Укорачиваются только метки, похожие на v3 onion-адрес: ровно 56 символов в
// алфавите base32 (a-z и 2-7). Осмысленные имена вроде «torch», «ahmia-clear» и
// «tornet» не трогаются, потому что они и так короткие и читаемые.
func displayEngineName(name string) string {
	trimmed := strings.TrimSpace(name)
	if trimmed == "" {
		return name
	}
	if !looksLikeOnionLabel(trimmed) {
		return trimmed
	}
	// Префикса в 8 символов достаточно, чтобы отличить движок глазами в списке
	// из нескольких записей, и при этом строка остаётся в одну линию.
	return "onion-" + trimmed[:8]
}

// looksLikeOnionLabel сообщает, похожа ли строка на метку v3 onion-адреса.
//
// Проверяются длина и алфавит, а не суффикс «.onion»: имя движка - это уже
// первая метка хоста, отделённая от домена, поэтому суффикса в ней нет.
func looksLikeOnionLabel(s string) bool {
	if len(s) != 56 {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 'a' && c <= 'z' {
			continue
		}
		if c >= '2' && c <= '7' {
			continue
		}
		return false
	}
	return true
}
