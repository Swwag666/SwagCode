package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// yesNo печатает булево значение по-русски. Отдельная функция, а не тернарный
// if на месте: строку пределов poolcheck читают и люди, и тесты, и «true» в
// русском выводе выглядело бы чужим словом.
func yesNo(v bool) string {
	if v {
		return "да"
	}
	return "нет"
}

// wantsJSON ищет флаг машинного вывода в аргументах до разбора команды.
//
// Значение флага после fs.Parse смотреть уже поздно: часть отказов происходит
// раньше (подкоманда не указана или не распознана), а часть - внутри самого
// Parse, где FlagSet с ExitOnError завершает процесс самостоятельно. Поиск по
// аргументам совпадает с тем, как флаг разбирают команды: распознаётся отдельный
// аргумент --json или -json, а не подстрока внутри другого аргумента.
func wantsJSON(args []string) bool {
	for _, a := range args {
		if a == "--json" || a == "-json" {
			return true
		}
	}
	return false
}

func fatalf(format string, args ...any) {
	msg := fmt.Sprintf(format, args...)
	fmt.Fprintf(os.Stderr, "ERROR: %s\n", msg)
	if jsonMode {
		// Машинный потребитель читает stdout: код возврата 1 говорит «отказ», но
		// причину он берёт из потока данных. Печать идёт через общий writeJSON, а
		// не собственным энкодером: страж TestJSONOutputGoesThroughWriteJSON
		// требует ровно одну точку сериализации, и обход её вернул бы команду,
		// которая отдаёт обрезанный JSON с кодом возврата 0.
		writeJSON(map[string]string{"error": msg})
	}
	// os.Exit не выполняет defer, поэтому без явного опустошения стека
	// аварийный выход оставлял tor-процесс сиротой и базу с несброшенным WAL.
	// Реестр опустошается ровно один раз: если очистка уже отработала, вызов
	// безопасен.
	RunShutdown()
	os.Exit(1)
}

// writeJSON сериализует значение в stdout с отступом в два пробела и завершает
// команду, если запись не удалась.
//
// Единая точка нужна не ради краткости. До правки в main.go было пятнадцать
// одинаковых троек «энкодер, отступ, Encode», и ошибку записи проверяли только
// три из них. В остальных двенадцати обрыв потока - закрытый пайп, оборванное
// соединение, кончившееся место - приводил к тому, что команда печатала
// обрезанный JSON и завершалась с кодом 0.
//
// Измерено на files --json: каталог из 400 записей, читающий конец stdout закрыт
// сразу после старта подпроцесса. Код возврата 0, stderr пуст, в поток ушла
// часть документа. Для скрипта-потребителя это худший из вариантов: разбор
// обрывается на середине, а сигнал говорит, что всё получилось.
//
// Отступ сохранён прежний: вывод команд читают глазами, а сжатие в одну строку
// изменило бы форму всех JSON-ответов сразу.
func writeJSON(v any) {
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		// Поток мёртв, поэтому машинный вывод выключается здесь же: fatalf в
		// режиме --json попытался бы допечатать JSON-ошибку в тот же stdout, а
		// та попытка снова сорвала бы запись и снова позвала fatalf. Измерено без
		// этой строки: 1 765 987 одинаковых сообщений, 113 МБ stderr и код
		// возврата 2 вместо 1.
		jsonMode = false
		fatalf("вывод: %v", err)
	}
}

// samePath сравнивает пути как файлы, а не как строки: Windows не различает регистр
// букв в пути, и запись той же базы в другом регистре прошла бы строковое
// сравнение, после чего команда удалила бы базу и скопировала её же на место.
func samePath(a, b string) bool {
	fa, err := os.Stat(a)
	if err != nil {
		return strings.EqualFold(filepath.Clean(a), filepath.Clean(b))
	}
	fb, err := os.Stat(b)
	if err != nil {
		return strings.EqualFold(filepath.Clean(a), filepath.Clean(b))
	}
	return os.SameFile(fa, fb)
}

// clipText обрезает длинный текст для сообщения об отказе. SQLite на побитой базе
// возвращает не одну строку, а список находок, и печатать его в отказе целиком
// смысла нет: причина видна в первых же.
func clipText(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n]) + "..."
}

func clipLine(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n]) + "..."
}
