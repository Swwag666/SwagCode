package main

import (
	"fmt"
	"os"
	"os/signal"
	"sync"
	"syscall"
)

// Реестр аварийной очистки.
//
// Проблема. fatalf вызывает os.Exit(1), а os.Exit не выполняет defer. В main.go
// 94 вызова fatalf, и часть из них срабатывает после того, как ресурсы уже
// получены: база открыта, поисковое ядро собрано, tor-демон запущен. Аварийный
// выход в этот момент оставлял tor-процесс сиротой (он продолжал жить и держать
// socks-порт), а базу - с несброшенным WAL.
//
// Править 94 места означало бы переписать половину команд. Вместо этого fatalf
// опустошает стек, в который ресурсы регистрируются при получении. Обычный путь
// завершения не меняется: defer остаётся defer, а регистрация снимает себя,
// поэтому двойного выполнения нет.
//
// Порядок LIFO, как у defer: tor закрывается раньше базы, потому что фоновая
// запись здоровья движков обращается к базе.

// exitHook - одна запись стека очистки.
//
// Хранится и передаётся по указателю намеренно: идентичность записи тогда
// определяется адресом, и снятие регистрации корректно даже если стек
// перестраивался другими регистрациями. Сравнение по имени или по указателю на
// функцию было бы хрупким: один ресурс можно закрыть дважды, а два разных
// ресурса одного типа дали бы одинаковое имя.
type exitHook struct {
	name   string
	fn     func() error
	closed bool
}

var (
	shutdownMu   sync.Mutex
	shutdownOnce sync.Once
	hooks        []*exitHook
)

// AtExit регистрирует функцию очистки и возвращает функцию, которая выполняет
// её и снимает регистрацию.
//
// Использование: `defer AtExit("база", st.Close)()`.
//
// Контракт возвращаемой функции намеренно совпадает с defer-семантикой: она
// ВЫПОЛНЯЕТ очистку, а не только убирает запись из реестра. Первая версия
// возвращала лишь снятие регистрации, и `defer AtExit("база", st.Close)()`
// оказывался ловушкой: регистрация снималась, а st.Close не вызывался вовсе.
// База оставалась открытой после возврата из команды, что на тестах выглядело как
// «TempDir RemoveAll cleanup: файл используется другим процессом», а в продакшне
// означало бы незакрытое соединение и несброшенный WAL при нормальном завершении.
//
// При нормальном завершении очистку выполняет defer. При аварийном выходе через
// fatalf запись остаётся в стеке, и её выполняет RunShutdown. Флаг closed и
// sync.Once гарантируют, что функция отработает ровно один раз любым из путей.
//
// Имя печатается, если очистка завершилась ошибкой: «tor: context deadline
// exceeded» объясняет, что именно не закрылось, а безымянная ошибка на этапе
// выхода бесполезна - процесс уже умирает и переспросить некого.
//
// Пустое имя или nil-функция игнорируются: регистрация заведомо пустого хука
// означала бы лишнюю запись в стеке и лишний вывод при ошибке.
func AtExit(name string, fn func() error) func() {
	if fn == nil {
		return func() {}
	}
	h := &exitHook{name: name, fn: fn}

	shutdownMu.Lock()
	hooks = append(hooks, h)
	shutdownMu.Unlock()

	var once sync.Once
	return func() {
		once.Do(func() {
			shutdownMu.Lock()
			h.closed = true
			for i, cur := range hooks {
				if cur == h {
					hooks = append(hooks[:i], hooks[i+1:]...)
					break
				}
			}
			shutdownMu.Unlock()

			if err := h.fn(); err != nil {
				fmt.Fprintf(os.Stderr, "очистка %s: %v\n", h.name, err)
			}
		})
	}
}

// AsError адаптирует функцию без возврата ошибки к сигнатуре хука.
//
// Нужна потому, что cleanup поискового ядра возвращает func(), а реестр хранит
// func() error: ошибка закрытия tor важна и должна печататься. Оборачивать
// каждый вызов замыканием на месте значило бы дублировать одну и ту же
// трёхстрочную конструкцию в 14 местах.
func AsError(fn func()) func() error {
	if fn == nil {
		return nil
	}
	return func() error {
		fn()
		return nil
	}
}

// RunShutdown опустошает стек очистки ровно один раз.
//
// Вызывается из fatalf перед os.Exit, из обработчика сигналов и из main при
// нормальном завершении. Идемпотентен через sync.Once: аварийный выход мог
// случиться после того, как очистка уже отработала, и повторное закрытие tor
// или базы вернуло бы ошибку, которая напугала бы пользователя на ровном месте.
//
// Ошибка одного хука не прерывает остальные. Сиротский tor-процесс и
// несброшенная база хуже, чем незакрытый один из нескольких ресурсов, поэтому
// цикл идёт до конца, а ошибки печатаются в stderr.
func RunShutdown() {
	shutdownOnce.Do(func() {
		shutdownMu.Lock()
		pending := hooks
		hooks = nil
		shutdownMu.Unlock()

		// LIFO: последний зарегистрированный закрывается первым.
		for i := len(pending) - 1; i >= 0; i-- {
			h := pending[i]
			if h.closed {
				continue
			}
			h.closed = true
			if err := h.fn(); err != nil {
				fmt.Fprintf(os.Stderr, "очистка %s: %v\n", h.name, err)
			}
		}
	})
}

// PendingShutdown возвращает число зарегистрированных хуков.
//
// Нужно тестам: проверить, что аварийный выход действительно опустошает стек,
// можно только увидев его содержимое. В продакшн-коде не используется.
func PendingShutdown() int {
	shutdownMu.Lock()
	defer shutdownMu.Unlock()
	return len(hooks)
}

// ResetShutdownForTest очищает стек и сбрасывает одноразовость.
//
// Вызывается только тестами: каждый тест обязан начинать с пустого стека, иначе
// хуки предыдущего теста выполнялись бы в чужом контексте. Сброс sync.Once
// возможен только заменой переменной, поэтому функция живёт в продакшн-файле, а
// не в _test.go - иначе пакет не собирался бы.
func ResetShutdownForTest() {
	shutdownMu.Lock()
	hooks = nil
	shutdownMu.Unlock()
	shutdownOnce = sync.Once{}
}

// NotifyShutdown ставит обработчик сигналов, который опустошает стек очистки и
// завершает процесс.
//
// Ctrl+C и SIGTERM ведут себя как fatalf: без обработчика os.Exit из defer не
// вызывался бы вовсе, и tor оставался бы сиротой при прерывании долгого поиска
// или разведки. Код выхода 130 - соглашение для прерывания по SIGINT
// (128 + номер сигнала 2).
//
// Канал буферизован на 1, как требует signal.Notify: без буфера сигнал,
// пришедший до входа в select, теряется.
func NotifyShutdown() {
	sig := make(chan os.Signal, 1)
	signal.Notify(sig, os.Interrupt, syscall.SIGTERM)
	go func() {
		s := <-sig
		fmt.Fprintf(os.Stderr, "\nполучен сигнал %s, останавливаюсь\n", s)
		RunShutdown()
		os.Exit(130)
	}()
}
