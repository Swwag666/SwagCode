package router

import "testing"

// Бытовые запросы обычного пользователя не должны уходить в deep-режим.
// Роутер ищет сигналы через strings.Contains, поэтому куски слов попадают в
// совпадение: "мотор" содержит "тор ", "диалог" содержит "лог ", "сливы"
// содержат "слив", "паста" содержит "паст".
//
// Цена ложного срабатывания высокая. Вместо быстрого поиска по обычному
// интернету запрос уходит в onion-поиск через tor: это в разы медленнее и
// возвращает не те результаты, которые человек спрашивал.
func TestRouteEverydayQueriesAreNotDeep(t *testing.T) {
	everyday := []struct {
		query string
		why   string
	}{
		{"какое моторное масло лучше залить", "«мотор» содержит «тор »"},
		{"трактор для фермы купить", "«трактор» содержит «тор »"},
		{"реакторный двигатель принцип работы", "«реактор» содержит «тор »"},
		{"детектор металла своими руками", "«детектор» содержит «тор »"},
		{"коллектор долгов как работает", "«коллектор» содержит «тор »"},
		{"диалог двух философов о свободе", "«диалог» содержит «лог »"},
		{"монолог из фильма иван васильевич", "«монолог» содержит «лог »"},
		{"рецепт со сливами и орехами", "«сливами» содержит «слив»"},
		{"сливочное масло как выбрать", "«сливочное» содержит «слив»"},
		{"паста карбонара рецепт", "«паста» содержит «паст»"},
		{"комбо в стрит файтер", "«комбо» содержит «combo»? нет, но проверяем"},
		{"дампы памяти как анализировать", "бытовое значение слова «дамп»"},
	}
	for _, c := range everyday {
		d := Route(c.query)
		if d.Mode == ModeDeep {
			t.Errorf("бытовой запрос ушёл в deep: %q (%s), причина: %s", c.query, c.why, d.Reason)
		}
	}
}

// Обратная сторона: настоящие запросы про утечки и onion обязаны оставаться
// в deep. Чинить ложные срабатывания за счёт потери настоящих нельзя.
func TestRouteRealDeepQueriesStillDeep(t *testing.T) {
	deep := []string{
		"найди onion сайты с книгами",
		"даркнет маркетплейсы список",
		"tor browser как настроить",
		"утечка данных компании",
		"слитая база пользователей",
		"exploit for CVE-2024-1234",
		"shodan search apache",
		"pastebin dump credentials",
		"leaked database archive",
		"комбо листы creds",
		"db dump mongodb",
	}
	for _, q := range deep {
		d := Route(q)
		if d.Mode != ModeDeep {
			t.Errorf("запрос про утечки/onion не попал в deep: %q -> %s (%s)", q, d.Mode, d.Reason)
		}
	}
}

// Stealth-сигналы страдают той же болезнью: это домены и названия сервисов, и
// искать их подстрокой внутри произвольного текста нельзя.
func TestRouteEverydayQueriesAreNotStealth(t *testing.T) {
	// Бытовые запросы, в которых не назван ни один антибот-сервис.
	everyday := []string{
		"книжные ярмарки в москве расписание",
		"как забронировать отель без предоплаты",
		"купить велосипед недорого с рук",
		"рейтинг продавцов на маркетплейсе",
	}
	for _, q := range everyday {
		d := Route(q)
		if d.Mode == ModeStealth {
			t.Errorf("бытовой запрос ушёл в stealth: %q, причина: %s", q, d.Reason)
		}
	}
}

func TestRouteFastSignalsStillWork(t *testing.T) {
	fast := []string{
		"новости про квантовые компьютеры",
		"погода в санкт-петербурге на неделю",
		"что такое энтропия определение",
		"wikipedia article about graphene",
	}
	for _, q := range fast {
		d := Route(q)
		if d.Mode != ModeFast {
			t.Errorf("быстрый информационный запрос ушёл в %s: %q (%s)", d.Mode, q, d.Reason)
		}
	}
}
